// Build the SDK from spec/openapi.json:
//   src/generated/      typed request functions, from @hey-api/openapi-ts
//   src/resources.gen.ts the client.emails.send() layer, from the x-sdk-group
//                       and x-sdk-method names the spec gives every operation
// Nothing in either output is edited by hand.
import { readFile, writeFile, rm } from "node:fs/promises";
import { createClient } from "@hey-api/openapi-ts";

const root = new URL("..", import.meta.url).pathname;
const spec = JSON.parse(await readFile(`${root}spec/openapi.json`, "utf8"));
const METHODS = ["get", "post", "put", "patch", "delete"];

await rm(`${root}src/generated`, { recursive: true, force: true });
await createClient({
  input: `${root}spec/openapi.json`,
  output: { path: `${root}src/generated`, importFileExtension: ".js" },
  plugins: ["@hey-api/client-fetch", "@hey-api/typescript", "@hey-api/sdk"],
  logs: { level: "silent" },
});

const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const camel = (s) => s.replace(/[_-](\w)/g, (_, c) => c.toUpperCase());
const deref = (schema) => {
  while (schema?.$ref) schema = spec.components.schemas[schema.$ref.split("/").pop()];
  return schema;
};
const successSchema = (op) => {
  for (const [code, res] of Object.entries(op.responses ?? {})) {
    if (code.startsWith("2")) return deref(res.content?.["application/json"]?.schema);
  }
};

// One tree of groups; each leaf is an operation.
const tree = { groups: new Map(), ops: [] };
const missing = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;
    const group = op["x-sdk-group"];
    const name = op["x-sdk-method"];
    if (!Array.isArray(group) || !name) {
      missing.push(op.operationId);
      continue;
    }
    let node = tree;
    for (const g of group) {
      if (!node.groups.has(g)) node.groups.set(g, { groups: new Map(), ops: [] });
      node = node.groups.get(g);
    }
    const params = op.parameters ?? [];
    const pathParams = [...path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    const query = params.filter((p) => p.in === "query");
    const result = successSchema(op);
    node.ops.push({
      id: op.operationId,
      name,
      method: method.toUpperCase(),
      path,
      summary: op.summary ?? op.operationId,
      pathParams,
      hasQuery: query.length > 0,
      queryRequired: query.some((p) => p.required),
      hasBody: Boolean(op.requestBody),
      bodyRequired: Boolean(op.requestBody?.required),
      idempotent: params.some((p) => p.in === "header" && p.name.toLowerCase() === "idempotency-key"),
      paginated:
        method === "get" &&
        query.some((p) => p.name === "after") &&
        deref(result?.properties?.data)?.type === "array" &&
        Boolean(result?.properties?.has_more),
    });
  }
}
if (missing.length) {
  throw new Error(`Operations without x-sdk-group/x-sdk-method: ${missing.join(", ")}`);
}

function emitOp(op, indent) {
  const T = pascal(op.id);
  const args = op.pathParams.map((p) => `${camel(p)}: string`);
  const call = [];
  if (op.pathParams.length) call.push(`path: { ${op.pathParams.map((p) => (camel(p) === p ? p : `${p}: ${camel(p)}`)).join(", ")} }`);
  if (op.hasBody) {
    args.push(`body${op.bodyRequired ? "" : "?"}: T.${T}Data["body"]`);
    call.push("body");
  }
  if (op.hasQuery) {
    args.push(`query${op.queryRequired ? "" : "?"}: T.${T}Data["query"]`);
    call.push("query");
  }
  args.push("options?: RequestOptions");
  const doc = `${indent}/** ${op.summary.replace(/\*\//g, "*\\/")}. \`${op.method} ${op.path}\` */\n`;
  let out =
    doc +
    `${indent}${op.name}: (${args.join(", ")}): Promise<Result<T.${T}Responses>> =>\n` +
    `${indent}  core.call(sdk.${op.id}, ${call.length ? `{ ${call.join(", ")} }` : "{}"}, options${op.idempotent ? ", true" : ""}),\n`;
  if (op.paginated) {
    const pageArgs = args.filter((a) => !a.startsWith("body"));
    out +=
      `${indent}/** Every item of ${op.name}, fetching the following pages as you iterate. */\n` +
      `${indent}${op.name}All: (${pageArgs.join(", ")}): AsyncIterable<ItemOf<Result<T.${T}Responses>>> =>\n` +
      `${indent}  core.paginate(sdk.${op.id}, { ${call.filter((c) => c !== "body").join(", ")} }, options),\n`;
  }
  return out;
}

function emitGroup(node, indent) {
  let out = "";
  for (const op of node.ops) out += emitOp(op, indent);
  for (const [name, child] of node.groups) {
    if (node.ops.some((o) => o.name === name)) throw new Error(`${name} is both a method and a group`);
    out += `${indent}${name}: {\n${emitGroup(child, indent + "  ")}${indent}},\n`;
  }
  return out;
}

const count = (node) => node.ops.length + [...node.groups.values()].reduce((n, g) => n + count(g), 0);
const source = `// Generated by scripts/generate.mjs from spec/openapi.json. Do not edit.
import * as sdk from "./generated/sdk.gen.js";
import type * as T from "./generated/types.gen.js";
import type { Core, ItemOf, RequestOptions, Result } from "./core.js";

export function createResources(core: Core) {
  return {
${emitGroup(tree, "    ")}  };
}

export type Resources = ReturnType<typeof createResources>;
`;
await writeFile(`${root}src/resources.gen.ts`, source);
console.log(`src/resources.gen.ts: ${count(tree)} operations`);
